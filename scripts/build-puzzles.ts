/**
 * Maintainer script: build Answer Sets from the committed content and pre-generate dated Puzzles.
 *
 *   npm run puzzles:build                              next 14 Puzzle Days from today (Sydney)
 *   npm run puzzles:build -- --from 2026-12-01 --days 7
 *   npm run puzzles:build -- --force                   regenerate dates that already have a Puzzle
 *   npm run puzzles:build -- --report                  only print each Template's Answer Set size and Tiers
 *
 * Reads (optional inputs may be absent):
 *   src/content/game-data/snapshot.json                the data snapshot (its patch is the data version)
 *   src/content/overlay/champions.json                 champion meta overlay (npm run data:overlay)
 *   src/content/templates/templates.json               Template definitions
 *   src/content/labels/approved.json                   approved mechanics labels (#9)
 *   src/content/familiarity/<snapshot patch>.json      Familiarity (#11); without it, Typicality only
 *   src/content/reviews/approved/<templateId>.json     approved Template reviews (#10): Typicality,
 *                                                       Too Clever, Gem; without one, defaults.
 *                                                       proposals/ is never read.
 *   src/content/puzzles/overrides.json                 { "<YYYY-MM-DD>": [seven Template ids] }
 *
 * Writes src/content/puzzles/<YYYY-MM-DD>.json (server-only: they hold Answer Sets) and regenerates
 * src/content/puzzles/index.ts, the manifest the app's PuzzleSource imports. Existing dated Puzzles
 * are kept (a live Puzzle must not change) and count toward the no-repeat rule.
 */
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {
  buildPrompt,
  generatePuzzles,
  type ChampionMetaOverlay,
  type FamiliarityData,
  type GeneratedPuzzle,
  type TemplateDefinition,
} from "../src/builder";
import type { GameDataSnapshot } from "../src/content/game-data/snapshot";
import { readApprovedReviews } from "../src/reviews/files";
import { approvedLabels } from "../src/content/labels";
import { FIRST_PUZZLE_DAY } from "../src/content/puzzles/config";
import { addDays, puzzleDayOf } from "../src/engine";

const content = (path: string) => fileURLToPath(new URL(`../src/content/${path}`, import.meta.url));
const PUZZLES_DIR = content("puzzles");
const DAY_FILE = /^(\d{4}-\d{2}-\d{2})\.json$/;

async function readJson<T>(path: string): Promise<T> {
  return JSON.parse(await readFile(path, "utf8")) as T;
}

async function readOptionalJson<T>(path: string): Promise<T | undefined> {
  return existsSync(path) ? readJson<T>(path) : undefined;
}

async function readExistingPuzzles(): Promise<Map<string, GeneratedPuzzle>> {
  const files = (await readdir(PUZZLES_DIR)).filter((f) => DAY_FILE.test(f)).sort();
  return new Map(
    await Promise.all(
      files.map(async (f) => [f.replace(".json", ""), await readJson<GeneratedPuzzle>(`${PUZZLES_DIR}/${f}`)] as const),
    ),
  );
}

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

/** One line per Prompt keeps the Answer Set readable in diffs. */
function puzzleJson(puzzle: GeneratedPuzzle): string {
  const { prompts, ...head } = puzzle;
  const headLines = Object.entries(head).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
  const promptLines = prompts.map((p) => `    ${JSON.stringify(p)}`);
  return `{\n${headLines.join(",\n")},\n  "prompts": [\n${promptLines.join(",\n")}\n  ]\n}\n`;
}

function manifest(days: readonly string[]): string {
  const name = (day: string) => `puzzle_${day.replaceAll("-", "_")}`;
  return [
    "// Generated by scripts/build-puzzles.ts. Do not edit by hand.",
    "// Server-only: these Puzzles hold Answer Sets and must never be imported by client components.",
    'import type { GeneratedPuzzle } from "@/builder";',
    ...days.map((day) => `import ${name(day)} from "./${day}.json";`),
    "",
    "export const datedPuzzles: Readonly<Record<string, GeneratedPuzzle>> = {",
    ...days.map((day) => `  "${day}": ${name(day)} as unknown as GeneratedPuzzle,`),
    "};",
    "",
  ].join("\n");
}

async function main() {
  const snapshot = await readJson<GameDataSnapshot>(content("game-data/snapshot.json"));
  const familiarity = await readOptionalJson<FamiliarityData>(content(`familiarity/${snapshot.patch}.json`));
  // Only approved reviews: proposals never reach a Puzzle. Throws on an inconsistent approval.
  const reviews = await readApprovedReviews(content("reviews"));
  const inputs = {
    snapshot,
    overlay: await readJson<ChampionMetaOverlay>(content("overlay/champions.json")),
    templates: await readJson<TemplateDefinition[]>(content("templates/templates.json")),
    labels: approvedLabels,
    familiarity,
    reviews,
  };
  console.log(
    `Data ${snapshot.patch}; Familiarity: ${familiarity ? "yes" : "none (Typicality only)"}; ` +
      `reviews: ${Object.keys(reviews).length}; labels: ${approvedLabels.length}`,
  );

  const prompts = inputs.templates.map((t) => buildPrompt(t, inputs));
  for (const p of prompts) {
    const tiers = Object.values(p.answerSet);
    const count = (tier: string) => tiers.filter((t) => t === tier).length;
    console.log(
      `  ${p.templateId.padEnd(32)} ${String(tiers.length).padStart(3)} answers ` +
        `(M${count("minion")} TC${count("too-clever")} K${count("kill")} T${count("triple-kill")} Q${count("quadra-kill")} G${count("pentakill")})`,
    );
  }
  if (process.argv.includes("--report")) return;

  const from = arg("from") ?? puzzleDayOf(Date.now());
  const days = Number(arg("days") ?? 14);
  const force = process.argv.includes("--force");
  const existing = await readExistingPuzzles();
  const dates = Array.from({ length: days }, (_, i) => addDays(from, i)).filter((d) => force || !existing.has(d));
  for (const d of dates) existing.delete(d);

  const generated = generatePuzzles({
    dates,
    prompts,
    firstPuzzleDay: FIRST_PUZZLE_DAY,
    dataVersion: snapshot.patch,
    history: Object.fromEntries([...existing].map(([day, p]) => [day, p.prompts.map((x) => x.templateId)])),
    overrides: await readOptionalJson<Record<string, string[]>>(`${PUZZLES_DIR}/overrides.json`),
  });
  for (const puzzle of generated) {
    await writeFile(`${PUZZLES_DIR}/${puzzle.puzzleDay}.json`, puzzleJson(puzzle));
    existing.set(puzzle.puzzleDay, puzzle);
    console.log(`#${puzzle.puzzleNumber} ${puzzle.puzzleDay}: ${puzzle.prompts.map((p) => p.templateId).join(", ")}`);
  }
  await writeFile(`${PUZZLES_DIR}/index.ts`, manifest([...existing.keys()].sort()));
  console.log(`Wrote ${generated.length} Puzzles; ${existing.size} dated Puzzles in the manifest.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
